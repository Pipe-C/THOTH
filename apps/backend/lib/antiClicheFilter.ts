// lib/antiClicheFilter.ts — Filter post-generation THOTH
// ─────────────────────────────────────────────────────────────
// Scans Gemini response and detect prohibited filler words.
// if found, mark the text for regeneration.
// Ver: COMPORTAMIENTO_DEL_ASISTENTE.md, section 3 y 8.
// ─────────────────────────────────────────────────────────────

// ─── List of prohibited filler words ──────────────────────────

const CLICHE_PATTERNS: RegExp[] = [
  /en conclusi[oó]n/gi,
  /en resumen/gi,
  /a modo de cierre/gi,
  /para finalizar/gi,
  /es importante destacar que/gi,
  /cabe resaltar que/gi,
  /vale la pena mencionar/gi,
  /un aspecto (clave|fundamental|crucial) es/gi,
  /juega un papel (crucial|fundamental|vital)/gi,
  /profundizar en el tema/gi,
  /ahondar en este aspecto/gi,
  /esto pone de relieve/gi,
  /esto evidencia/gi,
  /esto resalta la importancia de/gi,
  /en el mundo actual/gi,
  /en la era digital/gi,
  /en un mundo cada vez m[aá]s/gi,
  /no cabe duda de que/gi,
  /sin lugar a dudas/gi,
];

// ─── Analysis result ───────────────────────────────────

export interface FilterResult {
  /** Text passed filter of filler words */
  passed: boolean;
  /** List of found coincidences */
  detected: string[];
  /** Original text with modifications */
  originalText: string;
}

// ─── Function analysis ──────────────────────────────────────

/**
 * Scans `text` against list of prohibited filler words.
 * Does not modify text; only reports what was found.
 *
 * @param text Text generated by Gemini to analyze.
 * @returns    Object FilterResult with verdict and coincidences.
 */
export function analyzeText(text: string): FilterResult {
  const detected: string[] = [];

  for (const pattern of CLICHE_PATTERNS) {
    pattern.lastIndex = 0;
    let match: RegExpExecArray | null = pattern.exec(text);
    while (match !== null) {
      detected.push(match[0].toLowerCase());
      match = pattern.exec(text);
    }
  }

  return {
    passed: detected.length === 0,
    detected: [...new Set(detected)], // delete duplicates
    originalText: text,
  };
}

// ─── Corrected Prompt ─────────────────────────────────────

/**
 * Generate corrected prompt to request Gemini regenerate
 * deleted text and detected filler words.
 *
 * @param originalText Text that failed the filter.
 * @param detected     List of found filler words.
 * @returns            Prompt of regeneration ready to inject.
 */
export function buildRegenerationPrompt(
  originalText: string,
  detected: string[],
): string {
  const formattedDetected = detected.map((d) => `"${d}"`).join(', ');

  return `El siguiente texto contiene muletillas o frases de relleno de IA que deben eliminarse. Reescríbelo manteniendo exactamente el mismo contenido académico, pero sin usar estas expresiones detectadas: ${formattedDetected}.

Texto a reescribir:
${originalText}

Instrucciones de reescritura:
- No elimines ni cambies el contenido informativo.
- Reemplaza las muletillas por transiciones naturales o simplemente elimínalas si el párrafo fluye sin ellas.
- Mantén el tono y perfil académico del texto original.`;
}
